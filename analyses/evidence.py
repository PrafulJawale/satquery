"""Phase 13 -- evidence packages built FROM EXISTING results.

Nothing here computes an analysis. This module reads the result objects that
Phases 6-12 already produce and states, in serializable form, what was measured
and how the answer was reached. If a fact is not in the result, it is reported
as `"unavailable"` -- it is never inferred.

The explanation text is generated by templates with no language model, no
branching on data values beyond the four outcome classes (matches / zero
matches / partial unknown / all unknown), and no wording that turns a
measurement into a cause.

The boundary sentence is imported from `analyses.multi_condition.CAVEAT`. It is
deliberately NOT copied: one constant, one wording, three places that show it.
"""

from __future__ import annotations

import os
from typing import Any, Dict, List, Optional, Tuple

from core.evidence import (
    UNKNOWN_ALL,
    UNKNOWN_NONE,
    UNKNOWN_NOT_APPLICABLE,
    UNKNOWN_PARTIAL,
    UNAVAILABLE,
    EvidencePackage,
    EvidenceRecord,
    Lineage,
    counts_of,
    unknown_handling_for,
)

from .multi_condition import CAVEAT

# --------------------------------------------------------------------------- #
# small readers -- every one of them tolerates a missing field
# --------------------------------------------------------------------------- #


def _text(value: Any, default: str = UNAVAILABLE) -> str:
    text = str(value).strip() if value is not None else ""
    return text or default


def _as_dict(value: Any) -> Dict[str, Any]:
    return dict(value) if isinstance(value, dict) else {}


def _scene_label(path: Any) -> str:
    """A scene name, shortened to a file name only when it is a path."""
    text = _text(path, "")
    if not text:
        return UNAVAILABLE
    return os.path.basename(text) if ("/" in text or "\\" in text) else text


def _grid_of(result: Any) -> Dict[str, Any]:
    """The grid a result was computed on, from whichever field carries it."""
    grid = getattr(result, "grid", None)
    if isinstance(grid, dict) and grid:
        return _as_dict(grid)
    if grid is not None and hasattr(grid, "to_dict"):
        try:
            return _as_dict(grid.to_dict())
        except Exception:
            return {}
    return {}


def _cell_area(grid: Dict[str, Any]) -> float:
    """m² per cell, from the transform when the grid does not state it."""
    area = grid.get("cell_area_m2")
    if area:
        return float(area)
    transform = tuple(grid.get("transform") or ())
    if len(transform) >= 6:
        return abs(float(transform[0]) * float(transform[4]))
    resolution = grid.get("resolution_m")
    return float(resolution) ** 2 if resolution else 0.0


def _counts_from(entry: Dict[str, Any]) -> Dict[str, int]:
    """Normalise the two counting conventions in use.

    Phase 12 writes `matched` / `non_matching` / `insufficient`; Phase 9's
    `GridMask.counts()` writes `matching_cells` / `non_matching_cells` /
    `insufficient_cells`. Both mean the same three states, so they are folded
    into one shape here and nowhere else.
    """
    nested = _as_dict(entry.get("counts"))
    pick = lambda *names: next(
        (v for n in names if (v := entry.get(n, nested.get(n))) is not None), 0)
    return counts_of(
        matched=pick("matched", "matching_cells", "true"),
        non_matching=pick("non_matching", "non_matching_cells", "false"),
        insufficient=pick("insufficient", "insufficient_cells", "unknown"),
        total=pick("total", "valid_cells", "analysed"),
    )


def _dates_of(result: Any) -> Tuple[str, ...]:
    dates = getattr(result, "source_dates", None)
    if isinstance(dates, dict) and dates:
        before, after = dates.get("before"), dates.get("after")
        if before or after:
            return tuple(_text(d) for d in (before, after) if d)
        if dates.get("scene_date"):
            return (_text(dates.get("scene_date")),)
    before = getattr(result, "before_date", None)
    after = getattr(result, "after_date", None)
    if before or after:
        return tuple(_text(d) for d in (before, after) if d)
    return ()


# --------------------------------------------------------------------------- #
# threshold provenance wording -- ONE place, reused by the UI
# --------------------------------------------------------------------------- #
def threshold_origin_text(spec: Optional[Dict[str, Any]]) -> str:
    """Where a threshold came from, in the words Phase 12 already uses."""
    spec = _as_dict(spec)
    if not spec:
        return UNAVAILABLE
    provenance = _text(spec.get("provenance"), "")
    detail = _text(spec.get("detail"), "")
    if provenance == "user_specified":
        return "from your query."
    if provenance == "config_convention":
        return (f"a display/query convention ({detail}) — enabled by you, and "
                f"not a scientific classification.")
    if provenance == "relative":
        return (f"relative to this area ({detail}) — a comparison within the "
                f"selected area, not an absolute class.")
    return detail or provenance or UNAVAILABLE



def evidence_from_entry(entry: Any) -> Optional[EvidencePackage]:
    """Build a package from one chat-history entry.

    The app stores `AnalysisExecution.to_dict()` plus the live result object;
    this is the bridge that keeps the app from re-implementing the contract.
    Refusals and unsupported queries have nothing to explain, so they are not
    given a package at all -- they never carry a result.
    """
    if not isinstance(entry, dict):
        return None
    if str(entry.get("status", "")).upper() != "OK" or entry.get("result") is None:
        return None
    provenance = _as_dict(entry.get("provenance"))
    return build_evidence(
        query=_text(entry.get("query"), ""),
        normalized_query=_text(entry.get("normalized_query"), ""),
        intent=entry.get("intent") or UNAVAILABLE,
        status=str(entry.get("status", "") or ""),
        result=entry.get("result"),
        provenance=provenance,
        runtime_ms=provenance.get("runtime_ms"),
    )

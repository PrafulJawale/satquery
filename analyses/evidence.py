def condition_rows(package: EvidencePackage) -> List[Dict[str, Any]]:
    """One row per condition: what it was, where it came from, what it did."""
    rows: List[Dict[str, Any]] = []
    for record in package.records:
        if record.kind == "spectral":
            parameter = (f"Threshold: {record.operator or ''} {record.threshold}"
                         if record.threshold is not None else UNAVAILABLE)
            origin = threshold_origin_text(record.threshold_provenance)
        elif record.kind == "temporal":
            parameter = f"Change class: {_parameter_text(record)}"
            origin = ("Before " + record.source_dates[0]
                      if len(record.source_dates) > 0 else UNAVAILABLE)
            if len(record.source_dates) > 1:
                origin += f" → After {record.source_dates[1]}"
            origin += " · Phase 10 NDVI change"
        else:
            parameter = ("Water class: 80 · " if "distance_m" in record.parameters
                         else "Class: ") + _parameter_text(record) \
                if record.parameters else UNAVAILABLE
            origin = record.source_dataset
        rows.append({
            "condition": record.label,
            "source": record.source_dataset,
            "analysis": record.source_analysis,
            "parameter": parameter,
            "origin": origin,
            "matched": record.matched,
            "non_matching": record.non_matching,
            "unknown": record.unknown,
        })
    return rows


def source_rows(package: EvidencePackage) -> List[Dict[str, str]]:
    """The datasets and scenes an answer came from."""
    rows: List[Dict[str, str]] = []
    for source in package.sources:
        rows.append({
            "analysis": _text(source.get("analysis")),
            "dataset": _text(source.get("dataset")),
            "dates": ", ".join(source.get("dates") or ()) or UNAVAILABLE,
            "band_or_index": _text(source.get("band_or_index"), ""),
        })
    return rows


def _plain_number(value: Any) -> str:
    """3460320.0 -> '3460320'; 10.0 -> '10'; no exponent, no trailing zeros."""
    try:
        number = float(value)
    except Exception:
        return _text(value)
    text = f"{number:.6f}".rstrip("0").rstrip(".")
    return text or "0"


def grid_rows(package: EvidencePackage) -> List[Tuple[str, str]]:
    """The reproducibility facts, in the order Step 7 lists them."""
    grid = package.grid or {}
    transform = tuple(grid.get("transform") or ())
    # A composition carries its per-source alignment blocks nested under the
    # source name ("temporal": {...}); the reproducibility row wants the one
    # that actually produced the grid.
    alignment = package.alignment or {}
    for key in ("temporal", "spectral", "spatial"):
        nested = _as_dict(alignment.get(key))
        if nested and ("method" in nested or "resampled" in nested):
            alignment = nested
            break
    resampled = bool(alignment.get("resampled"))
    rows = [
        ("Query", package.query or UNAVAILABLE),
        ("Normalized query", package.normalized_query or UNAVAILABLE),
        ("Intent", package.intent or UNAVAILABLE),
        ("Analysis dates", (", ".join(package.combined.source_dates)
                            if package.combined and package.combined.source_dates
                            else "not recorded for this result")),
        ("CRS", _text(grid.get("crs"))),
        ("Grid", (f"{grid.get('width', UNAVAILABLE)} x "
                  f"{grid.get('height', UNAVAILABLE)} cells") if grid else UNAVAILABLE),
        ("Resolution", (f"{grid.get('resolution_m'):g} m"
                        if grid.get("resolution_m") else UNAVAILABLE)),
        ("Transform", ", ".join(_plain_number(v) for v in transform)
         if transform else UNAVAILABLE),
        ("Alignment method", _text(alignment.get("method")
                                   or alignment.get("grid_source"))),
        ("Resampling", UNAVAILABLE if not alignment else
         ("none — computed on the native grid" if not resampled
          else _text(alignment.get("resampling")))),
        ("Analysed cells", f"{package.analysed_cells:,}"),
        ("Undecided cells", f"{package.unknown_cells:,}"),
        ("Matched area", f"{package.matched_area_km2:,.3f} km²"),
        ("Unknown handling", package.unknown_handling),
        ("Runtime", f"{package.runtime_ms:,.1f} ms" if package.runtime_ms
         is not None else UNAVAILABLE),
    ]
    for name, spec in (package.threshold_provenance or {}).items():
        rows.append((f"Threshold — {name}", threshold_origin_text(_as_dict(spec))))
    return rows


